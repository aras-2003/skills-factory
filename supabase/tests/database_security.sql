DO $$
DECLARE
  item record;
BEGIN
  IF has_schema_privilege('anon', 'public', 'USAGE')
     OR has_schema_privilege('authenticated', 'public', 'USAGE') THEN
    RAISE EXCEPTION 'client roles retain public schema access';
  END IF;

  FOR item IN
    SELECT c.relname, c.relkind, c.relrowsecurity
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
      AND c.relname NOT LIKE 'pg_%' AND c.relname NOT LIKE 'sql_%'
  LOOP
    IF NOT item.relrowsecurity THEN
      RAISE EXCEPTION 'RLS is disabled for public.%', item.relname;
    END IF;
    IF has_table_privilege('anon', format('public.%I', item.relname), 'SELECT')
       OR has_table_privilege('anon', format('public.%I', item.relname), 'INSERT')
       OR has_table_privilege('authenticated', format('public.%I', item.relname), 'SELECT')
       OR has_table_privilege('authenticated', format('public.%I', item.relname), 'INSERT') THEN
      RAISE EXCEPTION 'client role has table access to public.%', item.relname;
    END IF;
    IF NOT has_table_privilege('service_role', format('public.%I', item.relname), 'SELECT') THEN
      RAISE EXCEPTION 'service_role lacks SELECT on public.%', item.relname;
    END IF;
  END LOOP;

  IF has_function_privilege('anon', 'public.try_numeric(text)', 'EXECUTE')
     OR has_function_privilege('authenticated', 'public.try_numeric(text)', 'EXECUTE')
     OR NOT has_function_privilege('service_role', 'public.try_numeric(text)', 'EXECUTE') THEN
    RAISE EXCEPTION 'try_numeric function grants do not match the private server-role contract';
  END IF;
END
$$;

CREATE TABLE public.default_acl_probe (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  value text NOT NULL
);

CREATE FUNCTION public.default_acl_probe_fn()
RETURNS integer LANGUAGE sql AS 'SELECT 1';

DO $$
BEGIN
  IF has_table_privilege('anon', 'public.default_acl_probe', 'SELECT')
     OR has_table_privilege('authenticated', 'public.default_acl_probe', 'SELECT')
     OR NOT has_table_privilege('service_role', 'public.default_acl_probe', 'INSERT') THEN
    RAISE EXCEPTION 'future table defaults are not least-privilege';
  END IF;
  IF has_sequence_privilege('anon', 'public.default_acl_probe_id_seq', 'USAGE')
     OR has_sequence_privilege('authenticated', 'public.default_acl_probe_id_seq', 'USAGE')
     OR NOT has_sequence_privilege('service_role', 'public.default_acl_probe_id_seq', 'USAGE') THEN
    RAISE EXCEPTION 'future sequence defaults are not least-privilege';
  END IF;
  IF has_function_privilege('anon', 'public.default_acl_probe_fn()', 'EXECUTE')
     OR has_function_privilege('authenticated', 'public.default_acl_probe_fn()', 'EXECUTE')
     OR has_function_privilege('service_role', 'public.default_acl_probe_fn()', 'EXECUTE') THEN
    RAISE EXCEPTION 'future functions must be private until explicitly granted';
  END IF;
END
$$;

SET ROLE anon;
DO $$
BEGIN
  BEGIN
    PERFORM 1 FROM public.accounts;
    RAISE EXCEPTION 'anon unexpectedly read private account data';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
  BEGIN
    INSERT INTO public.accounts(provider) VALUES ('synthetic-security-probe');
    RAISE EXCEPTION 'anon unexpectedly inserted private account data';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END
$$;
RESET ROLE;

SET ROLE authenticated;
DO $$
BEGIN
  BEGIN
    PERFORM 1 FROM public.accounts;
    RAISE EXCEPTION 'authenticated unexpectedly read private account data';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
  BEGIN
    INSERT INTO public.accounts(provider) VALUES ('synthetic-security-probe');
    RAISE EXCEPTION 'authenticated unexpectedly inserted private account data';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END
$$;
RESET ROLE;

SET ROLE service_role;
INSERT INTO public.accounts(provider) VALUES ('synthetic-security-probe');
SELECT 1 FROM public.current_positions LIMIT 1;
DELETE FROM public.accounts WHERE provider = 'synthetic-security-probe';
RESET ROLE;

DROP FUNCTION public.default_acl_probe_fn();
DROP TABLE public.default_acl_probe;
